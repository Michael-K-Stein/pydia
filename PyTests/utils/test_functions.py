@pytest.mark.parametrize("binary_type", ("exe", "dll"))
def test_find_function_by_pure_name(binary_type: str):
    FUNC_NAME = "MyFunc"
    with AdHocBinaryDataSource(
        f"""
extern "C" {{
int {FUNC_NAME}(int a);
int {FUNC_NAME}(int a) {{ return a; }}
static int main() {{ return {FUNC_NAME}(42); }}
}}
    """,
        binary_type=binary_type,
    ) as data_source:
        assert data_source.get_function(FUNC_NAME)


@pytest.mark.parametrize("binary_type", ("exe", "dll"))
def test_dont_find_function_by_pure_name(binary_type: str):
    with AdHocBinaryDataSource(
        """
extern "C" {
int MyFunc(int a);
int MyFunc(int a) { return a; }
static int main() { return MyFunc(42); }
}
    """,
        binary_type=binary_type,
    ) as data_source:
        for _ in range(0, 10):
            with pytest.raises(
                expected_exception=ValueError, match="Function by name not found!"
            ):
                data_source.get_function(
                    f"THIS_FUNCTION_nAmE_DoesNotEx1st_{hex(random.randint(0, 5000))[2:]}"
                )


